import { test, expect, Page } from '@playwright/test';
async function login(page: Page) {
  const profile = await (await page.request.get('http://127.0.0.1:4019/__test/profile')).json();
  await page.goto('/trips?search=MONITOR-FIXTURE-BROWSER-');
  await page.getByLabel('Tên đăng nhập').fill(profile.username);
  await page.getByLabel('Mật khẩu', { exact: true }).fill('Monitor-test-only-2026!');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Tra cứu và giám sát chuyến' })).toBeVisible();
}
test('read-only user: real list, detail, reload, POD, scope and responsive layout', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await login(page);
  await expect(page.getByRole('menuitem', { name: 'Điều Phối Thủ Công' })).toHaveCount(0);
  const search = page.getByRole('searchbox', { name: 'Tìm mã chuyến, biển số, tài xế' });
  await search.fill('MONITOR-FIXTURE-BROWSER-'); await search.press('Enter');
  const first = page.getByRole('button', { name: /^MONITOR-FIXTURE-/ }).first();
  const name = await first.textContent(); await first.click();
  await expect(page).toHaveURL(/trip=/);
  await expect(page.getByText('Kế hoạch và thực tế từng điểm', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText(name || '', { exact: true })).toBeVisible();
  await page.getByText(/2\. \[FIXTURE\] Delivery/).click();
  const open = page.getByRole('button', { name: 'Mở POD đã xác minh' });
  await expect(open).toBeVisible(); await open.click();
  await expect(page.getByRole('img', { name: 'Bằng chứng giao hàng của lần giao đã chọn' })).toBeVisible();
  expect(await page.getByRole('img', { name: 'Bằng chứng giao hàng của lần giao đã chọn' }).evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0);
  await page.getByRole('dialog').getByRole('button', { name: 'Đóng', exact: true }).click();
  await page.screenshot({ path: 'test-results/monitor-detail.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Quay lại danh sách' })).toBeVisible();
  await page.screenshot({ path: 'test-results/monitor-mobile-width.png', fullPage: true });
  await page.getByRole('button', { name: 'Quay lại danh sách' }).click();
  await expect(page).toHaveURL(/search=MONITOR-FIXTURE/);
  await expect(search).toHaveValue('MONITOR-FIXTURE-BROWSER-');
  expect(errors).toEqual([]);
});
test('HTTP failure stays an error and retry restores real backend data', async ({ page }) => {
  await login(page);
  await page.route('**/trip-monitoring?**', route => route.abort('failed'));
  await page.getByRole('button', { name: 'Tải lại', exact: true }).click();
  await expect(page.getByText('Không kết nối được backend. Vui lòng kiểm tra kết nối và thử lại.')).toBeVisible();
  await expect(page.getByRole('button', { name: /^MONITOR-FIXTURE-/ })).toHaveCount(0);
  await page.unroute('**/trip-monitoring?**');
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
  await expect(page.getByRole('button', { name: /^MONITOR-FIXTURE-/ }).first()).toBeVisible();
});
test('real Socket.IO invalidation, duplicates, old events and reconnect reload database', async ({ page, context, request }) => {
  await login(page);
  await page.getByRole('button', { name: /^MONITOR-FIXTURE-/ }).first().click();
  await expect(page.getByText('Đã kết nối thông báo thay đổi; dữ liệu lấy từ server')).toBeVisible();
  const id = new URL(page.url()).searchParams.get('trip');
  const response = await request.post('http://127.0.0.1:4019/__test/notify/' + id);
  expect(response.ok()).toBeTruthy(); const changed = await response.json();
  await expect(page.getByText(`${changed.version} / 2`, { exact: true })).toBeVisible();
  await context.setOffline(true);
  await expect(page.getByText('Chưa kết nối thông báo theo chi nhánh; tự tải lại mỗi 15–60 giây')).toBeVisible();
  const missed = await request.post('http://127.0.0.1:4019/__test/notify/' + id); const latest = await missed.json();
  await context.setOffline(false);
  await expect(page.getByText(`${latest.version} / 2`, { exact: true })).toBeVisible();
  await page.reload(); await expect(page.getByText(`${latest.version} / 2`, { exact: true })).toBeVisible();
});
test('late detail response cannot replace another trip; revocation clears open POD', async ({ page }) => {
  await login(page);
  const buttons = page.getByRole('button', { name: /^MONITOR-FIXTURE-/ });
  const firstName = await buttons.first().textContent();
  let release: () => void = () => {};
  const wait = new Promise<void>(resolve => { release = resolve; });
  let intercepted: () => void = () => {};
  const started = new Promise<void>(resolve => { intercepted = resolve; });
  let delayed = false;
  await page.route(/\/trip-monitoring\/[a-f0-9-]+$/, async route => {
    if (delayed) return route.continue();
    delayed = true;
    const response = await route.fetch(); intercepted(); await wait; await route.fulfill({ response });
  });
  await buttons.first().click(); await started;
  await page.getByRole('button', { name: 'Quay lại danh sách' }).click();
  const other = page.getByRole('button', { name: /^MONITOR-FIXTURE-/ }).filter({ hasNotText: firstName || 'unknown' }).first();
  const otherName = await other.textContent(); await other.click();
  await expect(page.getByText(otherName || '', { exact: true })).toBeVisible(); release();
  await expect(page.getByText(firstName || '', { exact: true })).toHaveCount(0);
  await page.getByText(/2\. \[FIXTURE\] Delivery/).click();
  await page.getByRole('button', { name: 'Mở POD đã xác minh' }).click();
  await expect(page.getByRole('img', { name: 'Bằng chứng giao hàng của lần giao đã chọn' })).toBeVisible();
  const revoked = await page.request.post('http://127.0.0.1:4019/__test/revoke-viewer');
  expect(revoked.ok()).toBeTruthy();
  await expect(page.getByRole('img', { name: 'Bằng chứng giao hàng của lần giao đã chọn' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Đăng xuất' }).click();
  await expect(page.getByRole('img', { name: 'Bằng chứng giao hàng của lần giao đã chọn' })).toHaveCount(0);
  await expect(page.getByLabel('Tên đăng nhập')).toBeVisible();
});
