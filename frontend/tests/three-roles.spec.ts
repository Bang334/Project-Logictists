test('ADMIN sees three assignable branch roles; changing a role invalidates the open session', async ({ page, browser }) => {
  await page.goto('/accounts'); await login(page, 'admin');
  await expect(page.getByRole('heading', { name: 'Quản lý tài khoản' })).toBeVisible();
  await page.getByRole('button', { name: 'Tạo tài khoản', exact: true }).click();
  await page.getByLabel('Vai trò', { exact: true }).click();
  for (const name of ['Trưởng chi nhánh (Trưởng điều phối)', 'Nhân viên quản lý tài nguyên', 'Điều phối viên vận tải', 'Tài xế (mobile)']) await expect(page.getByRole('option', { name, exact: true })).toBeVisible();
  await expect(page.getByRole('option', { name: /Xử lý đơn|xử lý đơn/ })).toHaveCount(0);
  await page.keyboard.press('Escape'); await page.getByRole('button', { name: 'Close', exact: true }).click();
  const context = await browser.newContext(); const staff = await context.newPage();
  await staff.goto('http://127.0.0.1:5182/'); await login(staff, 'resource');
  const profile = await staff.evaluate(async () => (await fetch('http://127.0.0.1:4022/auth/profile', { headers: { Authorization: 'Bearer ' + sessionStorage.getItem('tms_token') } })).json());
  const adminToken = await page.evaluate(() => sessionStorage.getItem('tms_token'));
  const headers = { Authorization: 'Bearer ' + adminToken };
  const detail = await (await page.request.get('http://127.0.0.1:4022/users/' + profile.id, { headers })).json();
  const changed = await page.request.patch('http://127.0.0.1:4022/users/' + profile.id, { headers, data: { fullName: detail.fullName, expectedUpdatedAt: detail.updatedAt, roleCode: 'TRANSPORT_DISPATCHER', branchIds: [profile.branches[0].id] } });
  expect(changed.status()).toBe(200);
  await staff.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(staff.getByLabel('Tên đăng nhập')).toBeVisible();
  await login(staff, 'resource');
  await expect(staff.getByRole('heading', { name: 'Quản lý đơn hàng' })).toBeVisible();
  await expect(staff.getByRole('menuitem', { name: 'Đội Xe & Tài Xế' })).toHaveCount(0);
  await context.close();
});
