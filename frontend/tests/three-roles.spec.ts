  await page.getByRole('menuitem', { name: 'Đơn hàng', exact: true }).click();
  await expect(page.getByText('ROLE-ORDER-0', { exact: true })).toBeVisible();
  await expect(page.getByText('ROLE-ORDER-1', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Tạo đơn nháp' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Sửa', exact: true })).toHaveCount(0);
