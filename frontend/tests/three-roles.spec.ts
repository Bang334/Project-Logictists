test('resource manager opens fleet and real schedules; direct orders URL is blocked', async ({ page }) => {
  await page.goto('/'); await login(page, 'resource');
  await expect(page.getByRole('heading', { name: 'Xe, tài xế và lịch khả dụng' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Tạo xe', exact: true })).toBeVisible();
  await expect(page.getByRole('menuitem', { name: 'Đơn hàng', exact: true })).toHaveCount(0);
  await expect(page.getByRole('menuitem', { name: 'Điều Phối Tự Động' })).toHaveCount(0);
  await page.getByRole('tab', { name: 'Tài xế', exact: true }).click();
  await page.getByRole('button', { name: 'Chi tiết / lịch', exact: true }).first().click();
  await expect(page.getByRole('button', { name: 'Thêm lịch', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Thêm lịch', exact: true }).click();
  const schedule = page.getByRole('dialog', { name: 'Thêm lịch', exact: true });
  const interval = schedule.locator('.ant-picker-range input');
  const tomorrow = new Date(Date.now() + 7 * 3600000 + 86400000).toISOString().slice(0, 10);
  const [year, month, day] = tomorrow.split('-'); const localDate = `${day}/${month}/${year}`;
  await interval.nth(0).fill(localDate + ' 07:30'); await interval.nth(0).press('Tab');
  await interval.nth(1).fill(localDate + ' 17:00'); await interval.nth(1).press('Tab');
  const ready = schedule.getByLabel('Sẵn sàng từ — giờ Việt Nam');
  await ready.fill(localDate + ' 07:30'); await ready.press('Enter');
  await schedule.getByLabel('Điểm tài xế sẵn sàng', { exact: true }).fill('Role test ready location');
  await schedule.getByLabel('Vĩ độ', { exact: true }).fill('10');
  await schedule.getByLabel('Kinh độ', { exact: true }).fill('106');
  await schedule.getByLabel('Lý do', { exact: true }).fill('Role browser shift');
  const saved = page.waitForResponse(response => response.request().method() === 'POST' && /\/fleet\/drivers\/[^/]+\/schedules$/.test(response.url()));
  await schedule.getByRole('button', { name: 'Lưu lịch', exact: true }).click();
  const response = await saved; expect(response.status()).toBe(201);
  const driverId = new URL(response.url()).pathname.split('/')[3];
  await expect(schedule).toBeHidden();
  await page.goto('/fleet?kind=drivers&resource=' + driverId);
  await expect(page.getByRole('cell', { name: 'Role browser shift', exact: true })).toBeVisible();
  await page.screenshot({ animations: 'disabled', path: 'test-results/three-roles/resource-schedules.png' });
  await page.goto('/orders'); await expect(page.getByText('Không có quyền truy cập trong phạm vi đang chọn')).toBeVisible();
});
