import { test, expect, Page } from '@playwright/test';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
const require = createRequire(import.meta.url);
const config = require('../../backend/node_modules/dotenv').parse(readFileSync('../backend/.env'));
const password: string = config.AUTH_DEMO_PASSWORD;
async function login(page: Page, username: string, secret = password) {
  await page.goto('/');
  await page.getByLabel('Tên đăng nhập').fill(username);
  await page.getByLabel('Mật khẩu', { exact: true }).fill(secret);
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Đăng xuất' })).toBeVisible();
}

test('branch create/reload/deactivate/reactivate with real backend', async ({ page }) => {
  await login(page, 'demo_auth_admin');
  await page.getByRole('menuitem', { name: 'Đội Xe & Tài Xế' }).click();
  await page.getByRole('tab', { name: 'Chi nhánh', exact: true }).click();
  await page.getByRole('button', { name: 'Tạo chi nhánh', exact: true }).click();
  const code = 'PW-' + randomUUID();
  await page.getByLabel('Mã chi nhánh', { exact: true }).fill(code);
  await page.getByLabel('Tên chi nhánh', { exact: true }).fill('[TEST] ' + code);
  await page.getByLabel('Địa chỉ quản lý', { exact: true }).fill('[TEST] User supplied address');
  await page.getByLabel('Vĩ độ thực tế').fill('0');
  await page.getByLabel('Kinh độ thực tế').fill('0');
  await page.getByRole('button', { name: 'Lưu chi nhánh' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.reload();
  await page.getByRole('tab', { name: 'Chi nhánh', exact: true }).click();
  await page.getByRole('searchbox', { name: 'Tìm chi nhánh' }).fill(code);
  await page.getByRole('searchbox', { name: 'Tìm chi nhánh' }).press('Enter');
  const row = page.getByRole('row').filter({ hasText: code });
  await expect(row).toBeVisible();
  await row.getByRole('button', { name: 'Chi tiết / sửa' }).click();
  await expect(page.getByText('Tọa độ GPS chi nhánh: 0.00000, 0.00000')).toBeVisible();
  await page.getByLabel('Tên Chi Nhánh', { exact: true }).fill('[TEST] Edited ' + code);
  await page.getByRole('button', { name: 'Lưu Thay Đổi Chi Nhánh' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(row).toContainText('[TEST] Edited ' + code);
  await row.getByRole('button', { name: 'Ngừng', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await expect(row.getByText('Đã ngừng', { exact: true })).toBeVisible();
  await row.getByRole('button', { name: 'Kích hoạt lại', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await expect(row.getByText('Hoạt động', { exact: true })).toBeVisible();
  await page.getByRole('searchbox', { name: 'Tìm chi nhánh' }).fill('DEMO-AUTH-A');
  await page.getByRole('searchbox', { name: 'Tìm chi nhánh' }).press('Enter');
  await page.getByRole('row').filter({ hasText: 'DEMO-AUTH-A' }).getByRole('button', { name: 'Ngừng', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('tài xế:');
});

test('own password change logs out; new password works after reload', async ({ page, request }) => {
  await login(page, 'demo_auth_admin');
  const token = await page.evaluate(() => sessionStorage.getItem('tms_token'));
  const profile = await request.get('http://localhost:4011/auth/profile', { headers: { Authorization: `Bearer ${token}` } });
  const branchId: string = (await profile.json()).branches[0].id;
  const username = 'pw_password_' + randomUUID();
  const response = await request.post('http://localhost:4011/users', { headers: { Authorization: `Bearer ${token}`, 'Idempotency-Key': randomUUID() }, data: { username, fullName: '[TEST] Password UI', password, roleCode: 'DISPATCHER', branchIds: [branchId] } });
  expect(response.status()).toBe(201);
  await page.getByRole('button', { name: 'Đăng xuất' }).click();
  await login(page, username);
  await page.getByRole('button', { name: 'Đổi mật khẩu', exact: true }).click();
  const replacement = 'Browser-test-only-new-password!';
  await page.getByLabel('Mật khẩu hiện tại').fill('Wrong-current-password!');
  await page.getByLabel('Mật khẩu mới', { exact: true }).fill(replacement);
  await page.getByLabel('Xác nhận mật khẩu mới').fill(replacement);
  await page.getByRole('button', { name: 'Đổi mật khẩu và đăng xuất' }).click();
  await expect(page.getByLabel('Mật khẩu hiện tại')).toHaveAttribute('aria-invalid', 'true');
  await expect(page.getByLabel('Mật khẩu mới', { exact: true })).toHaveValue(replacement);
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByLabel('Mật khẩu hiện tại').fill(password);
  await page.getByRole('button', { name: 'Đổi mật khẩu và đăng xuất' }).click();
  await expect(page.getByLabel('Tên đăng nhập')).toBeVisible();
  await login(page, username, replacement);
  await page.reload();
  await expect(page.getByRole('button', { name: 'Đăng xuất' })).toBeVisible();
});
